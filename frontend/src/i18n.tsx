export const dictionaries = { fr, en };
export type StringKey = keyof typeof fr;

const STORAGE_KEY = 'qv_language';

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: StringKey) => string };
const I18nContext = createContext<Ctx>({ lang: 'fr', setLang: () => {}, t: (k) => fr[k] });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('fr');

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((v) => {
      if (v === 'fr' || v === 'en') setLangState(v);
    });
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  };

  const value = useMemo<Ctx>(
    () => ({ lang, setLang, t: (k: StringKey) => dictionaries[lang][k] ?? dictionaries.fr[k] ?? k }),
    [lang]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
